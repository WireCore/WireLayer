// Builds @wirecore/wirelayer-css:
//   dist/components.css  the .wc-* classes as @apply rules – for projects with their own Tailwind v4 build
//   dist/wirecore.css    standalone: Tailwind preflight, WireLayer theme, fonts and all .wc-* classes, minified
//   dist/fonts/          the self-hosted font files (no CDN) and their licence (OFL.txt, SIL Open Font License 1.1)
//   dist/embed/          wirecore.css scoped to a placeholder and cut into parts – `wirelayer-css embed` (bin/)
//                        puts the chosen components together for pages with CSS of their own (src/embed.ts)
//   llms.txt, llms-full.txt  the class reference and the HTML guide for AI assistants (packages/mcp/scripts/render.ts)
// src/native-elements.css (native <dialog>) is added to all of them.
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile, optimize } from '@tailwindcss/node';
import * as recipes from '@wirecore/wirelayer-recipes';
import { cssLlms, stripMdx } from '../../mcp/scripts/render.ts';
import { scopeCss, splitLayers } from '../src/embed.ts';
import { classReference, generate } from '../src/generate.ts';

const root = fileURLToPath(new URL('..', import.meta.url));
const dist = join(root, 'dist');
rmSync(dist, { recursive: true, force: true });
mkdirSync(join(dist, 'fonts'), { recursive: true });

const generated = generate(recipes, recipes.twMergeConfig);
const { blocks } = generated;
const nativeElements = readFileSync(join(root, 'src/native-elements.css'), 'utf8');
const components = `${generated.css}\n${nativeElements}`;
writeFileSync(join(dist, 'components.css'), `/* Generated by @wirecore/wirelayer-css – do not edit */\n${components}`);

// Fonts: copy the Fontsource files and point the @font-face rules at ./fonts/
const fromTokens = createRequire(createRequire(import.meta.url).resolve('@wirecore/wirelayer-tokens/fonts.css'));
const fonts = ['@fontsource-variable/schibsted-grotesk', '@fontsource-variable/jetbrains-mono'];
const fontFaces = fonts
    .map((font) => {
        const file = fromTokens.resolve(`${font}/index.css`);
        return readFileSync(file, 'utf8').replace(/url\(\.\/files\/([^)]+)\)/g, (_, name: string) => {
            copyFileSync(join(dirname(file), 'files', name), join(dist, 'fonts', name));
            return `url(./fonts/${name})`;
        });
    })
    .join('\n');

// The fonts are under the SIL Open Font License 1.1, which has to travel with them: the copyright line of each
// font (first paragraph of Fontsource's LICENSE) and the licence text, which is the same for both
const licences = fonts.map((font) => {
    const text = readFileSync(join(dirname(fromTokens.resolve(`${font}/index.css`)), 'LICENSE'), 'utf8');
    const split = text.indexOf('\n\n');
    return { copyright: text.slice(0, split).trim(), body: text.slice(split).trim() };
});
if (new Set(licences.map((licence) => licence.body)).size !== 1) throw new Error('The font licences differ');
writeFileSync(
    join(dist, 'fonts', 'OFL.txt'),
    `${licences.map((licence) => licence.copyright).join('\n')}\n\n${licences[0]!.body}\n`
);

const input = `
@import 'tailwindcss' source(none);
@import '@wirecore/wirelayer-tokens/theme.css';
${components}`;
const compiler = await compile(input, { base: root, onDependency: () => {} });
const { code } = optimize(`${fontFaces}\n${compiler.build([])}`, { minify: true });
// wirecore.css contains Tailwind's preflight and theme layer (MIT) – keep its licence banner
const tailwind = JSON.parse(
    readFileSync(createRequire(import.meta.url).resolve('tailwindcss/package.json'), 'utf8')
) as { version: string };
const banners = [
    '/*! @wirecore/wirelayer-css – generated from @wirecore/wirelayer-recipes | MIT License */',
    `/*! tailwindcss v${tailwind.version} | MIT License | https://tailwindcss.com */`,
    '/*! Schibsted Grotesk, JetBrains Mono | SIL Open Font License 1.1 | fonts/OFL.txt */',
];
writeFileSync(join(dist, 'wirecore.css'), `${banners.join('\n')}\n${code}`);

// dist/embed/: the same CSS, each component (and src/native-elements.css) in a layer of its own, so it can be cut out
// after compiling – theme variables, preflight and @property rules stay together in base.css
const embed = join(dist, 'embed');
mkdirSync(join(embed, 'components'), { recursive: true });
const parted = [...blocks, { name: 'native-elements', css: nativeElements }]
    .map((block) => `@layer wc-embed-${block.name} {\n${block.css}\n}`)
    .join('\n');
const embedCompiler = await compile(
    `@import 'tailwindcss' source(none);\n@import '@wirecore/wirelayer-tokens/theme.css';\n${parted}`,
    { base: root, onDependency: () => {} }
);
const { parts, rest } = splitLayers(optimize(embedCompiler.build([]), { minify: true }).code, 'wc-embed-');
// Tailwind's licence banner is part of the compiled CSS here
writeFileSync(join(embed, 'base.css'), `${banners[0]}\n${scopeCss(rest, 'base')}`);
writeFileSync(join(embed, 'fonts.css'), `${banners[2]}\n${optimize(fontFaces, { minify: true }).code}`);
writeFileSync(join(embed, 'native-elements.css'), scopeCss(parts.get('native-elements') ?? '', 'components'));
for (const { name } of blocks)
    writeFileSync(join(embed, 'components', `${name}.css`), scopeCss(parts.get(name) ?? '', 'components'));
// The order of the components in wirecore.css – later ones may refine earlier ones (.wc-input-group .wc-input)
writeFileSync(join(embed, 'components.json'), `${JSON.stringify(blocks.map((block) => block.name))}\n`);

// The guides come from the collected docs (packages/mcp/data/components.json, checked against the sources in its test)
const collected = JSON.parse(readFileSync(join(root, '../mcp/data/components.json'), 'utf8')) as Parameters<
    typeof cssLlms
>[2];
const llms = cssLlms(
    classReference(recipes),
    stripMdx(readFileSync(join(root, 'src/Introduction.mdx'), 'utf8')),
    collected
);
writeFileSync(join(root, 'llms.txt'), llms.index);
writeFileSync(join(root, 'llms-full.txt'), llms.full);

const rules = blocks.reduce((sum, block) => sum + block.rules.length, 0);
console.log(`${blocks.length} components, ${rules} rules → dist/wirecore.css (${Math.round(code.length / 1024)} kB)`);
