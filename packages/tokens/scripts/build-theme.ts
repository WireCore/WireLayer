// Generates dist/theme.css (Tailwind v4 theme) from the compiled tokens (runs after tsc)
import { mkdirSync, writeFileSync } from 'node:fs';
import {
    colorDeclarations,
    colorTokens,
    colors,
    fonts,
    nativeExtraThemes,
    nativeFonts,
    radius,
    themes,
    themeToCss,
    themeToNativeCss,
    tracking,
} from '../dist/index.js';

// Built-in themes that override anything (the default "wirecore" theme is the base itself)
const themeRules = themes
    .filter((theme) => Object.keys(theme.colors.light).length || Object.keys(theme.colors.dark).length)
    .map(themeToCss)
    .join('\n\n');

// Without data-mode on <html> the page follows the system setting; data-mode="light"|"dark" forces a mode, also for a
// part of the page (a forced light part stays light on a dark system)
const css = `/* Generated by @wirecore/wirelayer-tokens – do not edit */
@custom-variant dark {
    &:where([data-mode=dark], [data-mode=dark] *) {
        @slot;
    }
    @media (prefers-color-scheme: dark) {
        &:where(:root:not([data-mode]), :root:not([data-mode]) *):not(:where([data-mode=light], [data-mode=light] *)) {
            @slot;
        }
    }
}

:root,
[data-mode=light] {
    color-scheme: light;
${colorDeclarations(colors.light)}
}

@media (prefers-color-scheme: dark) {
    /* Same specificity as [data-mode=dark], so the light overrides of a theme behave the same in both ways */
    :root:where(:not([data-mode])) {
        color-scheme: dark;
${colorDeclarations(colors.dark).replace(/^/gm, '    ')}
    }
}

[data-mode=dark] {
    color-scheme: dark;
${colorDeclarations(colors.dark)}
}

${themeRules}

@theme inline {
    --font-sans: ${fonts.sans.join(', ')};
    --font-mono: ${fonts.mono.join(', ')};
${colorTokens.map((token) => `    --color-${token}: var(--wc-${token});`).join('\n')}
${Object.entries(tracking)
    .map(([name, value]) => `    --tracking-${name}: ${value};`)
    .join('\n')}
}

/* Radii of cards, panels and popups: not inline, so the utilities read the variable and a theme (or :root) can change
   them at runtime */
@theme {
${Object.entries(radius)
    .map(([name, value]) => `    --radius-${name}: ${value};`)
    .join('\n')}
}

/* Animations that read variables set on the element itself (by Ark): "inline" puts the value into the utility.
   In the :root theme variable these var() would be resolved on :root, where they are not set – no animation. */
@theme inline {
    /* Toast: remaining time until it closes – Ark sets the duration as --duration */
    --animate-toast-progress: wc-toast-progress var(--duration) linear forwards;
    /* Marquee: Ark sets duration, delay, loop count and the distance (--marquee-translate) */
    --animate-marquee-x: wc-marquee-x var(--marquee-duration) linear var(--marquee-delay) var(--marquee-loop-count);
    --animate-marquee-y: wc-marquee-y var(--marquee-duration) linear var(--marquee-delay) var(--marquee-loop-count);
}

@theme {
    --animate-status-pulse: status-pulse 1.6s ease-in-out infinite;
    /* Open/close of overlays – popups move in from the side they open on (--wc-pop-x/-y) */
    --animate-fade-in: wc-fade-in 150ms ease-out;
    --animate-fade-out: wc-fade-out 120ms ease-in forwards;
    --animate-pop-in: wc-pop-in 160ms cubic-bezier(0.16, 1, 0.3, 1);
    --animate-pop-out: wc-pop-out 110ms ease-in forwards;
    --animate-dialog-in: wc-dialog-in 220ms cubic-bezier(0.16, 1, 0.3, 1);
    --animate-dialog-out: wc-dialog-out 140ms ease-in forwards;
    /* Accordion: Ark sets the content height as --height */
    --animate-collapse-in: wc-collapse-in 200ms ease-out;
    --animate-collapse-out: wc-collapse-out 160ms ease-in forwards;
    /* Drawer: slides in from the side it is attached to (--wc-slide-x/-y) */
    --animate-slide-in: wc-slide-in 260ms cubic-bezier(0.16, 1, 0.3, 1);
    --animate-slide-out: wc-slide-out 180ms ease-in forwards;
    /* Striped progress bar: the stripes move by one stripe width */
    --animate-progress-stripes: wc-progress-stripes 1s linear infinite;

    @keyframes status-pulse {
        50% {
            opacity: 0.35;
        }
    }
    @keyframes wc-fade-in {
        from {
            opacity: 0;
        }
    }
    @keyframes wc-fade-out {
        to {
            opacity: 0;
        }
    }
    @keyframes wc-pop-in {
        from {
            opacity: 0;
            transform: translate(var(--wc-pop-x, 0), var(--wc-pop-y, 0)) scale(0.96);
        }
    }
    @keyframes wc-pop-out {
        to {
            opacity: 0;
            transform: translate(var(--wc-pop-x, 0), var(--wc-pop-y, 0)) scale(0.96);
        }
    }
    @keyframes wc-dialog-in {
        from {
            opacity: 0;
            transform: translateY(8px) scale(0.96);
        }
    }
    @keyframes wc-dialog-out {
        to {
            opacity: 0;
            transform: translateY(4px) scale(0.98);
        }
    }
    @keyframes wc-collapse-in {
        from {
            height: 0;
        }
        to {
            height: var(--height);
        }
    }
    @keyframes wc-collapse-out {
        from {
            height: var(--height);
        }
        to {
            height: 0;
        }
    }
    @keyframes wc-slide-in {
        from {
            translate: var(--wc-slide-x, 0) var(--wc-slide-y, 0);
        }
    }
    @keyframes wc-slide-out {
        to {
            translate: var(--wc-slide-x, 0) var(--wc-slide-y, 0);
        }
    }
    @keyframes wc-progress-stripes {
        from {
            background-position: 1rem 0;
        }
        to {
            background-position: 0 0;
        }
    }
    @keyframes wc-marquee-x {
        to {
            transform: translateX(var(--marquee-translate));
        }
    }
    @keyframes wc-marquee-y {
        to {
            transform: translateY(var(--marquee-translate));
        }
    }
    @keyframes wc-toast-progress {
        from {
            scale: 1 1;
        }
        to {
            scale: 0 1;
        }
    }
}

@utility bg-glow {
    background-image: radial-gradient(90% 60% at 50% 0%, var(--wc-glow), transparent 70%);
}

@utility text-gradient {
    background: linear-gradient(180deg, var(--wc-fg) 35%, var(--wc-muted) 115%);
    -webkit-background-clip: text;
    background-clip: text;
    color: transparent;
}

@utility label-mono {
    font-family: var(--font-mono);
    font-size: 12px;
    letter-spacing: var(--tracking-label);
    text-transform: uppercase;
    color: var(--wc-muted);
}

@layer base {
    body {
        background-color: var(--wc-bg);
        color: var(--wc-fg);
        font-family: var(--font-sans);
        -webkit-font-smoothing: antialiased;
        -moz-osx-font-smoothing: grayscale;
    }
}
`;

const outDir = new URL('../dist/', import.meta.url);
mkdirSync(outDir, { recursive: true });
writeFileSync(new URL('theme.css', outDir), css);

// React Native (Uniwind): colours per theme × mode, fonts as one family per weight
// Uniwind declares the extra themes itself, but only after reading this file – declared here as well
// (same definition), so the @variant blocks below also compile on their own.
const nativeCss = `/* Generated by @wirecore/wirelayer-tokens – do not edit */
${nativeExtraThemes()
    .map((name) => `@custom-variant ${name} (&:where(.${name}, .${name} *));`)
    .join('\n')}

@layer theme {
    :root {
${themes.map(themeToNativeCss).join('\n')}
    }
}

@theme {
${Object.entries(nativeFonts)
    .map(([name, family]) => `    --font-${name}: '${family}';`)
    .join('\n')}
${Object.entries(radius)
    .map(([name, value]) => `    --radius-${name}: ${value};`)
    .join('\n')}
}
`;
writeFileSync(new URL('native.css', outDir), nativeCss);
