// Recurrence: Intl gives weekdays and months in the nominative ("środa", "grudzień"); after "w" the weekday takes
// the accusative ("w środę"), a month after a day or weekday the genitive ("24 grudnia", "2. poniedziałek maja").
const weekdayPattern = /poniedziałek|wtorek|środ|czwartek|piątek|sobot|niedziel/;
const weekdayAccusative: Record<string, string> = { środa: 'środę', sobota: 'sobotę', niedziela: 'niedzielę' };
const monthGenitive: Record<string, string> = {
    styczeń: 'stycznia',
    luty: 'lutego',
    marzec: 'marca',
    kwiecień: 'kwietnia',
    maj: 'maja',
    czerwiec: 'czerwca',
    lipiec: 'lipca',
    sierpień: 'sierpnia',
    wrzesień: 'września',
    październik: 'października',
    listopad: 'listopada',
    grudzień: 'grudnia',
};
const toAccusative = (text: string) => text.replace(/\p{L}+/gu, (word) => weekdayAccusative[word] ?? word);
const toGenitive = (text: string) => text.replace(/\p{L}+/gu, (word) => monthGenitive[word] ?? word);

