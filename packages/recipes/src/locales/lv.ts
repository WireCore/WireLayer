import { pluralText, type PluralForms, type Translations } from '../i18n.js';

type CalendarView = 'day' | 'month' | 'year';

/** The form for the count in Latvian plural rules (Intl.PluralRules), "{count}" replaced by the number */
const plural = (count: number, forms: PluralForms) => pluralText(forms, count, 'lv');

/**
 * Latvian categories: one (1, 21, 31 … but not 11) and zero (0, 10–20, 30 …) / other – zero takes the same plural
 * form as other, so only two forms are written.
 */
const forms = (one: string, other: string): PluralForms => ({ zero: other, one, other });

const characters = (count: number) => plural(count, forms('{count} rakstzīme', '{count} rakstzīmes'));

/** Weekday names from Intl (nominative) in the locative: ending 'ā' ("pirmdienā") or 'ās' ("pirmdienās") */
const weekdayCase = (text: string, ending: string) =>
    text.replace(
        /(?<!\p{L})(svēt|pirm|otr|treš|ceturt|piekt|sest)diena(?!\p{L})/giu,
        (_match, stem: string) => `${stem.toLowerCase()}dien${ending}`
    );

const monthGenitive: Record<string, string> = {
    janvāris: 'janvāra',
    februāris: 'februāra',
    marts: 'marta',
    aprīlis: 'aprīļa',
    maijs: 'maija',
    jūnijs: 'jūnija',
    jūlijs: 'jūlija',
    augusts: 'augusta',
    septembris: 'septembra',
    oktobris: 'oktobra',
    novembris: 'novembra',
    decembris: 'decembra',
};
/** Month names from Intl (nominative, possibly list-joined) in the genitive: "maija", "janvāra un jūlija" */
const monthsGenitive = (months: string) =>
    months.replace(/\p{L}+/gu, (word) => monthGenitive[word.toLowerCase()] ?? word);

