// Written for natural UI wording; should be proofread by a native speaker before release.
import { pluralText, type PluralForms, type Translations } from '../i18n.js';

type CalendarView = 'day' | 'month' | 'year';

/** The form for the count in Spanish plural rules (Intl.PluralRules), "{count}" replaced by the number */
const plural = (count: number, forms: PluralForms) => pluralText(forms, count, 'es');

const next: Record<CalendarView, string> = { day: 'Mes siguiente', month: 'Año siguiente', year: 'Década siguiente' };
const previous: Record<CalendarView, string> = {
    day: 'Mes anterior',
    month: 'Año anterior',
    year: 'Década anterior',
};
const viewNames: Record<CalendarView, string> = { day: 'días', month: 'meses', year: 'años' };

/** "1 carácter", "5 caracteres" */
const charCount = (count: number) => plural(count, { one: '{count} carácter', other: '{count} caracteres' });

/** 1 → "primer", 2 → "segundo" … (apocopated before a masculine noun: weekdays and "día"), then "6.º" */
const ordinals = ['primer', 'segundo', 'tercer', 'cuarto', 'quinto'];
const ordinal = (value: number) => ordinals[value - 1] ?? `${value}.º`;
/** Counted from the end: -1 → "último", -2 → "penúltimo", -3 → "antepenúltimo" */
const fromEnd = (value: number, noun: string) =>
    value === 1
        ? `último ${noun}`
        : value === 2
          ? `penúltimo ${noun}`
          : value === 3
            ? `antepenúltimo ${noun}`
            : `${ordinal(value)} ${noun} contando desde el final`;

