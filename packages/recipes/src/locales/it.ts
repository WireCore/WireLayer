const ordinals = ['primo', 'secondo', 'terzo', 'quarto', 'quinto'];
const fromEnd = ['ultimo', 'penultimo', 'terzultimo', 'quartultimo', 'quintultimo'];

/**
 * Ordinal with its article: 2 → "il secondo", -1 → "l'ultimo", feminine "la seconda" (domenica); beyond the fifth
 * "il 6°" (the caller adds "dalla fine" for negative positions)
 */
function ordinal(nth: number, feminine: boolean): string {
    const word = (nth > 0 ? ordinals : fromEnd)[Math.abs(nth) - 1];
    if (!word) return `${feminine ? 'la' : 'il'} ${Math.abs(nth)}${feminine ? 'ª' : '°'}`;
    const form = feminine ? `${word.slice(0, -1)}a` : word;
    return /^[aeiou]/.test(form) ? `l'${form}` : `${feminine ? 'la' : 'il'} ${form}`;
}

