// Recurrence: Intl gives the weekdays in the nominative ("hétfő"); "on Monday" and "the 2nd Monday of the month"
// need suffixed forms, which a suffix on an unknown word cannot produce – so they are looked up
const onWeekday: Record<string, string> = {
    hétfő: 'hétfőn',
    kedd: 'kedden',
    szerda: 'szerdán',
    csütörtök: 'csütörtökön',
    péntek: 'pénteken',
    szombat: 'szombaton',
    vasárnap: 'vasárnap',
};
const ofWeekday: Record<string, string> = {
    hétfő: 'hétfőjén',
    kedd: 'keddjén',
    szerda: 'szerdáján',
    csütörtök: 'csütörtökjén',
    péntek: 'péntekjén',
    szombat: 'szombatján',
    vasárnap: 'vasárnapján',
};
const weekdayPattern = /(?<!\p{L})(hétfő|kedd|szerda|csütörtök|péntek|szombat|vasárnap)(?!\p{L})/gu;
/** Suffix of a day of the month in a date: 1-jén (elsején), 2-án (másodikán), but 12-én, 22-én; 20-án, 23-án */
const daySuffix = (day: number) => {
    if (day === 1) return 'jén';
    if (day === 2 || day === 20 || day === 30) return 'án';
    return [3, 6, 8].includes(day % 10) ? 'án' : 'én';
};

