import { pluralText, type PluralForms, type Translations } from '../i18n.js';

type CalendarView = 'day' | 'month' | 'year';

/** The form for the count in Hungarian plural rules (Intl.PluralRules), "{count}" replaced by the number */
const plural = (count: number, forms: PluralForms) => pluralText(forms, count, 'hu');

// Hungarian keeps the noun singular after a number, so one and other share the form
const chars = (count: number) => plural(count, { one: '{count} karakter', other: '{count} karakter' });
const items = (count: number) => plural(count, { one: '{count} elem', other: '{count} elem' });
const rows = (count: number) => plural(count, { one: '{count} sor', other: '{count} sor' });
const cells = (count: number) => plural(count, { one: '{count} cella', other: '{count} cella' });
const degrees = (count: number) => plural(count, { one: '{count} fok', other: '{count} fok' });

/** "3. pozíció (összesen 7)" – avoids the article a/az before a number */
const position = (index: number, count: number) => `${index}. pozíció (összesen ${count})`;

