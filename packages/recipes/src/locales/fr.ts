// French texts of the components – every key of Translations (see ../i18n.ts). Not built in, so they cost nothing
// until imported: registerLocale('fr', fr) at app start, or <LocaleProvider locale="fr-FR" :translations="fr">.
// Written for natural UI wording; should be proofread by a native speaker before release.
import { pluralText, type PluralForms, type Translations } from '../i18n.js';

type CalendarView = 'day' | 'month' | 'year';

/** The form for the count in French plural rules (Intl.PluralRules), "{count}" replaced by the number */
const plural = (count: number, forms: PluralForms) => pluralText(forms, count, 'fr');

const characters = (count: number) => plural(count, { one: '{count} caractère', other: '{count} caractères' });
const items = (count: number) => plural(count, { one: '{count} élément', other: '{count} éléments' });
const matches = (count: number) => plural(count, { one: '{count} résultat', other: '{count} résultats' });
const maxSelected = (max: number) =>
    plural(max, { one: 'Sélection limitée à {count} élément', other: 'Sélection limitée à {count} éléments' });

/** 1 → "1er", 2 → "2e" */
const ordinal = (value: number) => (value === 1 ? '1er' : `${value}e`);
/** "le lundi", "l'avant-dernier lundi" */
const withArticle = (what: string) => (/^[aeiou]/i.test(what) ? `l'${what}` : `le ${what}`);
/** "de mai", "d'avril" */
const ofMonth = (month: string) => (/^[aeiou]/i.test(month) ? `d'${month}` : `de ${month}`);

