const items = (count: number) => plural(count, { one: '{count} item', other: '{count} items' });
const chars = (count: number) => plural(count, { one: '{count} teken', other: '{count} tekens' });
const cells = (count: number) => plural(count, { one: '{count} cel', other: '{count} cellen' });
const changes = (count: number) => plural(count, { one: '{count} wijziging', other: '{count} wijzigingen' });
const suggestions = (count: number) => plural(count, { one: '{count} suggestie', other: '{count} suggesties' });
const results = (count: number) => plural(count, { one: '{count} resultaat', other: '{count} resultaten' });

/** Counted from the end: 1 → "de laatste maandag", 2 → "de voorlaatste maandag", 3 → "de op 2 na laatste maandag" */
const fromEnd = (n: number, noun: string) =>
    n === 1 ? `de laatste ${noun}` : n === 2 ? `de voorlaatste ${noun}` : `de op ${n - 1} na laatste ${noun}`;

