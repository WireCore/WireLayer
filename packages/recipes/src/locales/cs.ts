// Recurrence wording: Intl gives weekday and month names in the nominative ("středa", "prosinec"), the phrases need
// the accusative after "v" ("ve středu"), an ordinal that agrees with the weekday ("druhou středu", "druhé pondělí")
// and the genitive or locative of the month ("24. prosince", "v prosinci").
const weekdayForms: Record<string, { accusative: string; ending: string }> = {
    pondělí: { accusative: 'pondělí', ending: 'é' },
    úterý: { accusative: 'úterý', ending: 'é' },
    středa: { accusative: 'středu', ending: 'ou' },
    čtvrtek: { accusative: 'čtvrtek', ending: 'ý' },
    pátek: { accusative: 'pátek', ending: 'ý' },
    sobota: { accusative: 'sobotu', ending: 'ou' },
    neděle: { accusative: 'neděli', ending: 'ou' },
};
const monthForms: Record<string, { genitive: string; locative: string }> = {
    leden: { genitive: 'ledna', locative: 'lednu' },
    únor: { genitive: 'února', locative: 'únoru' },
    březen: { genitive: 'března', locative: 'březnu' },
    duben: { genitive: 'dubna', locative: 'dubnu' },
    květen: { genitive: 'května', locative: 'květnu' },
    červen: { genitive: 'června', locative: 'červnu' },
    červenec: { genitive: 'července', locative: 'červenci' },
    srpen: { genitive: 'srpna', locative: 'srpnu' },
    září: { genitive: 'září', locative: 'září' },
    říjen: { genitive: 'října', locative: 'říjnu' },
    listopad: { genitive: 'listopadu', locative: 'listopadu' },
    prosinec: { genitive: 'prosince', locative: 'prosinci' },
};
/** "v", or "ve" before a cluster: "v pondělí", "ve středu", "ve druhou středu" */
const inPreposition = (phrase: string) => (/^(st|čt|tř|dr|v|f)/.test(phrase) ? 've' : 'v');
/** Ordinal as a word up to 5 ("druhou", "třetí"), above as a number ("6.") */
const ordinal = (n: number, ending: string) =>
    ['', 'první', `druh${ending}`, 'třetí', `čtvrt${ending}`, `pát${ending}`][n] || `${n}.`;
/** Month names (also a list "květen a červen") in another case */
const monthCase = (names: string, form: 'genitive' | 'locative') =>
    names.replace(/\p{L}+/gu, (name) => monthForms[name]?.[form] ?? name);

