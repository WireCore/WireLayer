// Portuguese (European, pt-PT) texts of the components – every key of Translations (see ../i18n.ts). Not built in, so
// they cost nothing until imported: registerLocale('pt', pt) at app start, or <LocaleProvider locale="pt-PT"
// :translations="pt">. Brazilian Portuguese builds on these in ./pt-BR.ts.
// Written for natural UI wording; should be proofread by a native speaker before release.
import { pluralText, type PluralForms, type Translations } from '../i18n.js';

type CalendarView = 'day' | 'month' | 'year';

/** The form for the count in European Portuguese plural rules (0 is plural there), "{count}" replaced by the number */
const plural = (count: number, forms: PluralForms) => pluralText(forms, count, 'pt-PT');

const characters: PluralForms = { one: '{count} carácter', other: '{count} caracteres' };
const degrees: PluralForms = { one: '{count} grau', other: '{count} graus' };

const next: Record<CalendarView, string> = { day: 'Mês seguinte', month: 'Ano seguinte', year: 'Década seguinte' };
const previous: Record<CalendarView, string> = {
    day: 'Mês anterior',
    month: 'Ano anterior',
    year: 'Década anterior',
};
const viewNames: Record<CalendarView, string> = { day: 'dias', month: 'meses', year: 'anos' };

// Recurrence: nthWeekday, monthDay, inMonth and dayOfMonth start with the article ("a 2.ª segunda-feira", "o dia
// 15"); `on` turns it into "na"/"no". Plain weekday lists from Intl become the habitual "às segundas-feiras".
const masculineDay = (weekday: string) => /^(sábado|domingo)/.test(weekday);
const withEm = (text: string) => text.replace(/(^|, | e )([ao]) /g, '$1n$2 ');
const everyWeekday = (days: string) =>
    days.replace(/(?:segunda|terça|quarta|quinta|sexta)-feira|sábado|domingo/g, (day) =>
        day.endsWith('-feira') ? `às ${day.replace(/-feira$/, 's-feiras')}` : `aos ${day}s`
    );

