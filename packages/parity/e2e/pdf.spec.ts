import { expect, test, type Page } from '@playwright/test';
import { openStory } from './story.ts';

// PdfViewer on pdf.js with the sample PDF (apps/storybook/public/pdf): 3 pages, links, outline, tagged structure
async function openViewer(page: Page, story = 'playground') {
    await openStory(page, `media-pdfviewer--${story}`);
    const viewer = page.getByRole('region', { name: 'PDF document' });
    await expect(viewer.getByRole('status').filter({ hasText: 'PDF loaded, 3 pages' })).toBeAttached();
    return viewer;
}

test.describe('PdfViewer', () => {
    test('loads the PDF: pages with text layer and structure, links, page field', async ({ page }) => {
        const viewer = await openViewer(page);
        await expect(viewer.getByRole('textbox', { name: 'Page' })).toHaveValue('1');
        await expect(viewer.getByRole('textbox', { name: 'Page' })).toHaveAccessibleDescription('of 3');
        const first = viewer.getByRole('region', { name: 'Page 1' });
        // Text layer: selectable text over the canvas, mapped to the PDF's tags (heading)
        await expect(first.locator('.textLayer')).toContainText(
            'This PDF was generated by hand for the Storybook examples'
        );
        // Tagged PDF: the structure tree (inside the canvas) names the text layer's parts as heading, paragraph …
        const heading = first.locator('.structTree [role="heading"][aria-level="1"]');
        const owned = await heading.getAttribute('aria-owns');
        await expect(first.locator(`.textLayer [id="${owned}"]`)).toHaveText('WireLayer sample document');
        await expect(first.locator('canvas').first()).toBeVisible();
        // Annotation layer: the external link opens in a new tab
        await expect(first.locator('.annotationLayer a[href="https://example.com/"]')).toHaveAttribute(
            'target',
            '_blank'
        );
    });

    test('the toolbar is one tab stop, arrow keys move inside it (also past the page field)', async ({ page }) => {
        const viewer = await openViewer(page);
        const toolbar = viewer.getByRole('toolbar', { name: 'PDF tools' });
        await page.keyboard.press('Tab');
        await expect(toolbar.getByRole('button', { name: 'Sidebar' })).toBeFocused();
        await page.keyboard.press('ArrowRight');
        // At the first page "Previous page" is aria-disabled but stays reachable
        await expect(toolbar.getByRole('button', { name: 'Previous page' })).toBeFocused();
        await page.keyboard.press('ArrowRight');
        const field = toolbar.getByRole('textbox', { name: 'Page' });
        await expect(field).toBeFocused();
        // In the field the arrows move the caret first, at its end they leave it
        await page.keyboard.press('End');
        await page.keyboard.press('ArrowRight');
        await expect(toolbar.getByRole('button', { name: 'Next page' })).toBeFocused();
        await page.keyboard.press('Tab');
        await expect(viewer.getByRole('document', { name: 'Document pages' })).toBeFocused();
    });

    test('keyboard in the page area: Page Down/Up, End and Home change the page', async ({ page }) => {
        const viewer = await openViewer(page);
        const field = viewer.getByRole('textbox', { name: 'Page' });
        await viewer.getByRole('document', { name: 'Document pages' }).focus();
        await page.keyboard.press('PageDown');
        await expect(field).toHaveValue('2');
        await expect(viewer.getByRole('status').filter({ hasText: 'Page 2 of 3' })).toBeAttached();
        await page.keyboard.press('End');
        await expect(field).toHaveValue('3');
        await page.keyboard.press('PageUp');
        await expect(field).toHaveValue('2');
        await page.keyboard.press('Home');
        await expect(field).toHaveValue('1');
        // Typing a page number
        await field.fill('3');
        await page.keyboard.press('Enter');
        await expect(field).toHaveValue('3');
    });

    test('zoom: Ctrl+plus/minus/0 in the viewer, buttons and the zoom list', async ({ page }) => {
        const viewer = await openViewer(page);
        const zoom = viewer.getByRole('combobox', { name: 'Zoom' });
        await expect(zoom).toHaveText('Page width');
        await viewer.getByRole('document', { name: 'Document pages' }).focus();
        await page.keyboard.press('Control+0');
        await expect(zoom).toHaveText('100%');
        await page.keyboard.press('Control+=');
        await expect(zoom).toHaveText('125%');
        await page.keyboard.press('Control+-');
        await page.keyboard.press('Control+-');
        await expect(zoom).toHaveText('75%');
        await viewer.getByRole('button', { name: 'Zoom in' }).click();
        await expect(zoom).toHaveText('100%');
        await zoom.click();
        await page.getByRole('option', { name: 'Whole page' }).click();
        await expect(zoom).toHaveText('Whole page');
    });

    test('search: Ctrl+F opens it, matches are counted and highlighted, Escape closes it', async ({ page }) => {
        const viewer = await openViewer(page);
        await viewer.getByRole('document', { name: 'Document pages' }).focus();
        await page.keyboard.press('Control+f');
        const field = viewer.getByRole('searchbox', { name: 'Search in document' });
        await expect(field).toBeFocused();
        await field.fill('Offer');
        const status = viewer.getByRole('search').getByRole('status');
        await expect(status).toHaveText('Match 1 of 3');
        await expect(viewer.locator('.textLayer .highlight').first()).toBeAttached();
        await expect(viewer.getByRole('textbox', { name: 'Page' })).toHaveValue('2');
        await page.keyboard.press('Enter');
        await expect(status).toHaveText('Match 2 of 3');
        await page.keyboard.press('Shift+Enter');
        await expect(status).toHaveText('Match 1 of 3');
        // Case-sensitive: "Offer" is not in the text (only "offer")
        await viewer.getByRole('button', { name: 'Match case' }).click();
        await expect(status).toHaveText('No matches');
        await field.focus();
        await page.keyboard.press('Escape');
        await expect(field).toBeHidden();
        await expect(viewer.getByRole('button', { name: 'Search', exact: true })).toBeFocused();
    });

    test('side bar: thumbnails mark the current page, the outline jumps', async ({ page }) => {
        const viewer = await openViewer(page, 'sidebar');
        const thumbnails = viewer.getByRole('tabpanel', { name: 'Pages' });
        await expect(thumbnails.getByRole('button', { name: 'Page 1' })).toHaveAttribute('aria-current', 'page');
        await thumbnails.getByRole('button', { name: 'Page 2' }).click();
        await expect(viewer.getByRole('textbox', { name: 'Page' })).toHaveValue('2');
        await expect(thumbnails.getByRole('button', { name: 'Page 2' })).toHaveAttribute('aria-current', 'page');
        await viewer.getByRole('tab', { name: 'Contents' }).click();
        const outline = viewer.getByRole('tree', { name: 'Contents' });
        await expect(outline.getByRole('treeitem', { name: 'Search' })).toBeVisible();
        await outline.getByRole('treeitem', { name: 'Contact' }).click();
        await expect(viewer.getByRole('textbox', { name: 'Page' })).toHaveValue('3');
    });

    test('internal link in the PDF jumps to its page', async ({ page }) => {
        const viewer = await openViewer(page);
        await viewer.locator('.annotationLayer [data-internal-link] a').first().click();
        await expect(viewer.getByRole('textbox', { name: 'Page' })).toHaveValue('3');
    });

    test('controlled: page and zoom follow the app, goToPage and search via ref', async ({ page }) => {
        const viewer = await openViewer(page, 'controlled');
        const summary = page.getByText(/^Page \d of \d · Zoom/);
        await expect(summary).toHaveText('Page 1 of 3 · Zoom 1');
        await page.getByRole('button', { name: 'Go to contact page' }).click();
        await expect(summary).toHaveText('Page 3 of 3 · Zoom 1');
        await page.getByRole('button', { name: '150%' }).click();
        await expect(viewer.getByRole('combobox', { name: 'Zoom' })).toHaveText('150%');
        await viewer.getByRole('button', { name: 'Zoom in' }).click();
        await expect(summary).toHaveText('Page 3 of 3 · Zoom 2');
        // The search starts on the current page (3): its match is the third
        await page.getByRole('button', { name: 'Search for “offer”' }).click();
        await expect(viewer.getByRole('search').getByRole('status')).toHaveText('Match 3 of 3');
    });

    test('download saves the original file', async ({ page }) => {
        const viewer = await openViewer(page);
        const download = page.waitForEvent('download');
        await viewer.getByRole('button', { name: 'Download' }).click();
        expect((await download).suggestedFilename()).toBe('sample.pdf');
    });

    test('print renders every page into a hidden frame and opens the print dialog', async ({ page }) => {
        // The print dialog is replaced: count the page images the frame holds, then report it closed
        await page.addInitScript(() => {
            window.print = () => {
                if (window === window.top) return;
                (window.top as unknown as { printStyle: string }).printStyle =
                    document.querySelector('style')?.textContent ?? '';
                (window.top as unknown as { printed: number }).printed = document.images.length;
                window.dispatchEvent(new Event('afterprint'));
            };
        });
        const viewer = await openViewer(page);
        await viewer.getByRole('button', { name: 'Print' }).click();
        await expect.poll(() => page.evaluate(() => (window as unknown as { printed?: number }).printed)).toBe(3);
        await expect(page.locator('iframe')).toHaveCount(0);
        // Each page is printed in its own size (named pages); the sample is A4 portrait throughout
        expect(await page.evaluate(() => (window as unknown as { printStyle: string }).printStyle)).toContain(
            '@page s0{size:595pt 842pt;margin:0}'
        );
    });

    test('the text layer can be switched off and on again; the page stays', async ({ page }) => {
        const viewer = await openViewer(page, 'layers');
        await viewer.getByRole('textbox', { name: 'Page' }).fill('2');
        await page.keyboard.press('Enter');
        await expect(viewer.getByRole('textbox', { name: 'Page' })).toHaveValue('2');
        await expect(viewer.locator('.textLayer').first()).toBeAttached();
        await page.getByRole('button', { name: 'Hide text layer' }).click();
        await expect(viewer.locator('.textLayer')).toHaveCount(0);
        await expect(viewer.getByRole('region', { name: 'Page 2' }).locator('canvas').first()).toBeVisible();
        await expect(viewer.getByRole('textbox', { name: 'Page' })).toHaveValue('2');
        await page.getByRole('button', { name: 'Hide text layer' }).click();
        await expect(viewer.locator('.textLayer').first()).toBeAttached();
        await expect(viewer.getByRole('region', { name: 'Page 2' }).locator('.textLayer')).toContainText(/\S/);
    });

    test('password: a dialog asks for it, a wrong one is reported', async ({ page }) => {
        await openStory(page, 'media-pdfviewer--password');
        const dialog = page.getByRole('dialog', { name: 'Protected PDF' });
        await expect(dialog).toBeVisible();
        const field = dialog.getByLabel('Password', { exact: true });
        await field.fill('wrong');
        await page.keyboard.press('Enter');
        await expect(dialog.getByText('The password is wrong. Please try again.')).toBeVisible();
        await field.fill('wirecore');
        await dialog.getByRole('button', { name: 'Open', exact: true }).click();
        await expect(dialog).toBeHidden();
        const viewer = page.getByRole('region', { name: 'PDF document' });
        await expect(viewer.getByRole('textbox', { name: 'Page' })).toHaveAccessibleDescription('of 3');
    });

    test('error: a missing file shows a message', async ({ page }) => {
        // Not openStory: the failed request keeps the network from going idle
        await page.goto('/iframe.html?id=media-pdfviewer--load-error&viewMode=story&globals=locale:en-US');
        await expect(page.getByRole('alert')).toHaveText('The PDF was not found.');
    });
});
