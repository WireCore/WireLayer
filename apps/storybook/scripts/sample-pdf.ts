// Writes the sample PDFs of the PdfViewer stories (public/pdf): three A4 pages with text, an external and an internal
// link, an outline and a tagged structure (headings, paragraphs, links, artifacts) – plus the same document encrypted
// with the user password "wirecore" (RC4 128 bit, standard security handler revision 3).
// Written by hand without a PDF library, so the files are our own: node apps/storybook/scripts/sample-pdf.ts
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';

type Value = number | boolean | null | Name | Text | Ref | Raw | Value[] | { [key: string]: Value };
class Name {
    readonly name: string;
    constructor(name: string) {
        this.name = name;
    }
}
class Text {
    readonly text: string;
    constructor(text: string) {
        this.text = text;
    }
}
class Ref {
    readonly id: number;
    constructor(id: number) {
        this.id = id;
    }
}
class Raw {
    readonly raw: string;
    constructor(raw: string) {
        this.raw = raw;
    }
}
const n = (name: string) => new Name(name);
const s = (text: string) => new Text(text);
const r = (id: number) => new Ref(id);

interface PdfObject {
    id: number;
    value: Value;
    stream?: Buffer;
}

// WinAnsiEncoding is Latin-1 for the letters used here
const latin1 = (text: string) => Buffer.from(text, 'latin1');
const escape = (text: string) => text.replace(/[\\()]/g, (char) => `\\${char}`);

// Widths of Helvetica / Helvetica-Bold (1/1000 em) for the link areas – average values are enough here
const textWidth = (text: string, size: number, bold = false) => text.length * size * (bold ? 0.58 : 0.52);

interface Line {
    tag: 'H1' | 'H2' | 'P' | 'Link';
    text: string;
    size: number;
    y: number;
    /** Index of the link annotation on the page */
    link?: number;
}

interface PageSpec {
    lines: Line[];
    links: { line: number; url?: string; page?: number; y?: number }[];
}

