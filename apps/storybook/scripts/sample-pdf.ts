mkdirSync(target, { recursive: true });
const document = build();
writeFileSync(new URL('sample.pdf', target), write(document));
writeFileSync(new URL('sample-password.pdf', target), write(document, { user: 'wirecore', owner: 'wirecore-owner' }));
