const PAGE_WIDTH = 595;
const PAGE_HEIGHT = 842;
const MARGIN = 56;

function build(): { objects: PdfObject[]; root: number; info: number } {
    const objects: PdfObject[] = [];
    let next = 1;
    const reserve = () => next++;
    const add = (id: number, value: Value, stream?: Buffer) => objects.push({ id, value, stream });

    const catalog = reserve();
    const pagesId = reserve();
    const outlines = reserve();
    const structRoot = reserve();
    const documentElem = reserve();
    const parentTree = reserve();
    const info = reserve();
    const regular = reserve();
    const bold = reserve();
    const pageIds = pages.map(() => reserve());
    const contentIds = pages.map(() => reserve());

    const documentKids: Ref[] = [];
    const parentTreeNums: [number, Value][] = [];
    let nextStructParent = pages.length;

    pages.forEach((page, index) => {
        const pageId = pageIds[index]!;
        const annotIds = page.links.map(() => reserve());
        const mcidElems: Ref[] = [];
        const linkElems = new Map<number, number>();
        // The frame at the top is decoration – an artifact, not part of the structure
        let content =
            '/Artifact BMC\n0.93 0.95 0.98 rg\n40 736 515 60 re f\n0.36 0.42 0.95 rg\n40 736 6 60 re f\nEMC\n';
        page.lines.forEach((line, mcid) => {
            const font = line.tag === 'H1' || line.tag === 'H2' ? '/F2' : '/F1';
            const color = line.tag === 'Link' ? '0.13 0.3 0.8 rg' : '0.1 0.1 0.15 rg';
            content += `/${line.tag === 'Link' ? 'Link' : line.tag} <</MCID ${mcid}>> BDC\nBT ${font} ${line.size} Tf ${color} ${MARGIN} ${line.y} Td (${escape(line.text)}) Tj ET\n`;
            if (line.tag === 'Link') {
                const width = textWidth(line.text, line.size);
                content += `0.13 0.3 0.8 RG 0.6 w ${MARGIN} ${line.y - 2} m ${MARGIN + width} ${line.y - 2} l S\n`;
            }
            content += 'EMC\n';
            const elem = reserve();
            mcidElems.push(r(elem));
            if (line.link !== undefined) linkElems.set(line.link, elem);
            const kids: Value =
                line.link !== undefined
                    ? [mcid, { Type: n('OBJR'), Obj: r(annotIds[line.link]!), Pg: r(pageId) }]
                    : mcid;
            add(elem, { Type: n('StructElem'), S: n(line.tag), P: r(documentElem), Pg: r(pageId), K: kids });
            documentKids.push(r(elem));
        });
        // Page number in the footer (artifact)
        content += `/Artifact BMC\nBT /F1 9 Tf 0.45 0.45 0.5 rg ${PAGE_WIDTH - MARGIN - 40} 40 Td (Page ${index + 1} of ${pages.length}) Tj ET\nEMC\n`;
        add(contentIds[index]!, {}, latin1(content));
        parentTreeNums.push([index, mcidElems]);

        const annots = page.links.map((link, linkIndex) => {
            const line = page.lines[link.line]!;
            const width = textWidth(line.text, line.size);
            const rect = [MARGIN, line.y - 4, MARGIN + width, line.y + line.size];
            const structParent = nextStructParent++;
            parentTreeNums.push([structParent, r(linkElems.get(linkIndex)!)]);
            const target: Record<string, Value> = link.url
                ? { A: { S: n('URI'), URI: s(link.url) } }
                : { Dest: [r(pageIds[link.page!]!), n('XYZ'), 0, link.y ?? PAGE_HEIGHT, null] };
            add(annotIds[linkIndex]!, {
                Type: n('Annot'),
                Subtype: n('Link'),
                Rect: rect,
                Border: [0, 0, 0],
                Contents: s(line.text),
                StructParent: structParent,
                ...target,
            });
            return r(annotIds[linkIndex]!);
        });

        add(pageId, {
            Type: n('Page'),
            Parent: r(pagesId),
            MediaBox: [0, 0, PAGE_WIDTH, PAGE_HEIGHT],
            Resources: { Font: { F1: r(regular), F2: r(bold) } },
            Contents: r(contentIds[index]!),
            StructParents: index,
            Tabs: n('S'),
            ...(annots.length ? { Annots: annots } : {}),
        });
    });

    // Outline: Introduction, Details (Search, Zoom), Contact
    const outlineIds = { intro: reserve(), details: reserve(), search: reserve(), zoom: reserve(), contact: reserve() };
    const dest = (page: number, y = PAGE_HEIGHT): Value => [r(pageIds[page]!), n('XYZ'), 0, y, null];
    add(outlines, {
        Type: n('Outlines'),
        First: r(outlineIds.intro),
        Last: r(outlineIds.contact),
        Count: 5,
    });
    add(outlineIds.intro, {
        Title: s('Introduction'),
        Parent: r(outlines),
        Next: r(outlineIds.details),
        Dest: dest(0),
    });
    add(outlineIds.details, {
        Title: s('Details'),
        Parent: r(outlines),
        Prev: r(outlineIds.intro),
        Next: r(outlineIds.contact),
        First: r(outlineIds.search),
        Last: r(outlineIds.zoom),
        Count: 2,
        Dest: dest(1),
    });
    add(outlineIds.search, {
        Title: s('Search'),
        Parent: r(outlineIds.details),
        Next: r(outlineIds.zoom),
        Dest: dest(1, 736),
    });
    add(outlineIds.zoom, {
        Title: s('Zoom'),
        Parent: r(outlineIds.details),
        Prev: r(outlineIds.search),
        Dest: dest(1, 660),
    });
    add(outlineIds.contact, { Title: s('Contact'), Parent: r(outlines), Prev: r(outlineIds.details), Dest: dest(2) });

    add(catalog, {
        Type: n('Catalog'),
        Pages: r(pagesId),
        Outlines: r(outlines),
        MarkInfo: { Marked: true },
        StructTreeRoot: r(structRoot),
        Lang: s('en-US'),
        ViewerPreferences: { DisplayDocTitle: true },
    });
    add(pagesId, { Type: n('Pages'), Kids: pageIds.map(r), Count: pages.length });
    add(structRoot, {
        Type: n('StructTreeRoot'),
        K: r(documentElem),
        ParentTree: r(parentTree),
        ParentTreeNextKey: nextStructParent,
    });
    add(documentElem, { Type: n('StructElem'), S: n('Document'), P: r(structRoot), K: documentKids });
    // The number tree's keys must be in ascending order
    add(parentTree, { Nums: parentTreeNums.sort(([a], [b]) => a - b).flat() });
    add(info, {
        Title: s('WireLayer sample document'),
        Author: s('WireLayer'),
        Creator: s('apps/storybook/scripts/sample-pdf.ts'),
    });
    const font = (base: string): Value => ({
        Type: n('Font'),
        Subtype: n('Type1'),
        BaseFont: n(base),
        Encoding: n('WinAnsiEncoding'),
    });
    add(regular, font('Helvetica'));
    add(bold, font('Helvetica-Bold'));
    objects.sort((a, b) => a.id - b.id);
    return { objects, root: catalog, info };
}

// Standard security handler, revision 3 (ISO 32000-1, 7.6.3): RC4 with a 128-bit key
const PADDING = Buffer.from('28bf4e5e4e758a4164004e56fffa01082e2e00b6d0683e802f0ca9fe6453697a', 'hex');
const md5 = (...parts: Buffer[]) => createHash('md5').update(Buffer.concat(parts)).digest();
function rc4(key: Buffer, data: Buffer): Buffer {
    const state = Array.from({ length: 256 }, (_, i) => i);
    for (let i = 0, j = 0; i < 256; i++) {
        j = (j + state[i]! + key[i % key.length]!) & 255;
        [state[i], state[j]] = [state[j]!, state[i]!];
    }
    const out = Buffer.alloc(data.length);
    for (let k = 0, i = 0, j = 0; k < data.length; k++) {
        i = (i + 1) & 255;
        j = (j + state[i]!) & 255;
        [state[i], state[j]] = [state[j]!, state[i]!];
        out[k] = data[k]! ^ state[(state[i]! + state[j]!) & 255]!;
    }
    return out;
}
const pad = (password: string) => Buffer.concat([latin1(password), PADDING]).subarray(0, 32);
const xorKey = (key: Buffer, i: number) => Buffer.from(key.map((byte) => byte ^ i));

interface Encryption {
    key: Buffer;
    dict: Value;
}

function encryption(user: string, owner: string, id: Buffer): Encryption {
    const permissions = -3904; // print and copy allowed
    let ownerKey = md5(pad(owner));
    for (let i = 0; i < 50; i++) ownerKey = md5(ownerKey);
    let o = rc4(ownerKey, pad(user));
    for (let i = 1; i <= 19; i++) o = rc4(xorKey(ownerKey, i), o);
    const p = Buffer.alloc(4);
    p.writeInt32LE(permissions);
    let key = md5(pad(user), o, p, id);
    for (let i = 0; i < 50; i++) key = md5(key);
    let u = rc4(key, md5(PADDING, id));
    for (let i = 1; i <= 19; i++) u = rc4(xorKey(key, i), u);
    u = Buffer.concat([u, Buffer.alloc(16)]);
    return {
        key,
        dict: {
            Filter: n('Standard'),
            V: 2,
            R: 3,
            Length: 128,
            O: new Raw(`<${o.toString('hex')}>`),
            U: new Raw(`<${u.toString('hex')}>`),
            P: permissions,
        },
    };
}

/** Key of one object: MD5 of the file key, the object number (3 bytes) and the generation (2 bytes) */
const objectKey = (key: Buffer, id: number) =>
    md5(key, Buffer.from([id & 255, (id >> 8) & 255, (id >> 16) & 255, 0, 0])).subarray(0, 16);

function serialize(value: Value, encrypt?: (data: Buffer) => Buffer): string {
    if (value === null) return 'null';
    if (typeof value === 'number' || typeof value === 'boolean') return String(value);
    if (value instanceof Name) return `/${value.name}`;
    if (value instanceof Ref) return `${value.id} 0 R`;
    if (value instanceof Raw) return value.raw;
    if (value instanceof Text) {
        const bytes = latin1(value.text);
        return encrypt ? `<${encrypt(bytes).toString('hex')}>` : `(${escape(value.text)})`;
    }
    if (Array.isArray(value)) return `[${value.map((item) => serialize(item, encrypt)).join(' ')}]`;
    return `<< ${Object.entries(value)
        .map(([key, item]) => `/${key} ${serialize(item, encrypt)}`)
        .join(' ')} >>`;
}

function write({ objects, root, info }: ReturnType<typeof build>, encrypted?: { user: string; owner: string }): Buffer {
    const id = md5(latin1(`wirecore-sample${encrypted ? '-encrypted' : ''}`));
    const security = encrypted ? encryption(encrypted.user, encrypted.owner, id) : undefined;
    const chunks: Buffer[] = [Buffer.from('%PDF-1.7\n%\xe2\xe3\xcf\xd3\n', 'latin1')];
    let length = chunks[0]!.length;
    const offsets: number[] = [];
    const push = (chunk: Buffer) => {
        chunks.push(chunk);
        length += chunk.length;
    };
    const all = [...objects];
    const encryptId = security ? all.length + 1 : undefined;
    if (security) all.push({ id: encryptId!, value: security.dict });
    for (const object of all) {
        offsets[object.id] = length;
        const crypt =
            security && object.id !== encryptId
                ? (data: Buffer) => rc4(objectKey(security.key, object.id), data)
                : undefined;
        if (object.stream) {
            const data = crypt ? crypt(object.stream) : object.stream;
            const dict = { ...(object.value as Record<string, Value>), Length: data.length };
            push(latin1(`${object.id} 0 obj\n${serialize(dict, crypt)}\nstream\n`));
            push(data);
            push(latin1('\nendstream\nendobj\n'));
        } else {
            push(latin1(`${object.id} 0 obj\n${serialize(object.value, crypt)}\nendobj\n`));
        }
    }
    const xref = length;
    const size = all.length + 1;
    let table = `xref\n0 ${size}\n0000000000 65535 f \n`;
    for (let i = 1; i < size; i++) table += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
    const trailer: Record<string, Value> = {
        Size: size,
        Root: r(root),
        Info: r(info),
        ID: [new Raw(`<${id.toString('hex')}>`), new Raw(`<${id.toString('hex')}>`)],
        ...(encryptId ? { Encrypt: r(encryptId) } : {}),
    };
    push(latin1(`${table}trailer\n${serialize(trailer)}\nstartxref\n${xref}\n%%EOF\n`));
    return Buffer.concat(chunks);
}

